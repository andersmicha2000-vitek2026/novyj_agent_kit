#!/usr/bin/env bash
# Механический скан русского текста на маркеры ИИ-письма.
# Использование: bash check.sh файл.md   |   cat текст | bash check.sh
#                bash check.sh --selftest
set -u

scan() {
  local text="$1" total=0 words
  words=$(printf '%s' "$text" | grep -oP '\S+' | wc -l)
  [ "$words" -eq 0 ] && { echo "пустой текст"; return 1; }

  # категория|человекочитаемое имя|regex (PCRE, без учёта регистра)
  local rules=(
'ТИРЕ|длинное тире|[—–]'
'НЕВИДИМКИ|невидимые символы|[\x{00A0}\x{00AD}\x{200B}-\x{200F}\x{202F}\x{2060}\x{FEFF}]'
'РАЗГОН|вводные-разгон|(стоит (отметить|подчеркнуть|заметить)|следует отметить|нельзя не отметить|важно понимать|важно отметить|на самом деле|как известно|не секрет,? что|давайте (разберёмся|разберемся|рассмотрим)|в современном мире|в наши дни|в мире, где|итак,|таким образом,|в заключение|подводя итог)'
'ШТАМП|канцелярит и штампы|(ключев(ой|ым|ые|ая) (фактор|роль|аспект|элемент)|играет (важную|ключевую) роль|комплексн(ый|ое) (подход|решение)|оптимальное решение|широкий (спектр|ассортимент)|инновационн|уникальн(ый|ое|ая) (предложение|решение|возможность)|эффективн(ый|ое) (инструмент|решение)|вывести на новый уровень|раскрыть (потенциал|возможности)|погрузиться в мир|в этой статье мы)'
'НАРЕЧИЕ|наречия-костыли|(действительно|буквально|поистине|крайне важно|невероятно|поразительно|попросту говоря)'
'ПРОТИВОПОСТ|бинарные «не X, а Y»|(это не [а-яё]+,? (а|это) |не просто [а-яё]+,? а |дело не в [а-яё]+,? а в )'
'ЭМОДЗИ|эмодзи-буллеты|^[[:space:]]*[\x{2700}-\x{27BF}\x{1F300}-\x{1FAFF}\x{2705}\x{274C}\x{2728}]'
'ЖИРНЫЙ_ПУНКТ|списки «**Слово:** текст»|^[[:space:]]*[-*•][[:space:]]*\*\*[^*]+\*\*[[:space:]]*[:—-]'
'ПОДЛИЗ|служебная вежливость|(надеюсь,? (это|эта информация) (помож|будет полезн)|если у вас (есть|остались) вопросы|буду рад помочь|отличный вопрос)'
  )

  echo "маркеры:"
  for rule in "${rules[@]}"; do
    IFS='|' read -r code name re <<< "$rule"
    local n
    n=$(printf '%s' "$text" | grep -o -i -P "(*UTF)(*UCP)$re" 2>/dev/null | wc -l)
    n=${n:-0}
    [ "$n" -gt 0 ] && printf '  %s: %s
' "$name" "$n"
    total=$((total + n))
  done

  local per1000=$(( total * 1000 / (words > 0 ? words : 1) ))
  echo
  echo "слов: $words   маркеров: $total   на 1000 слов: $per1000"
  if   [ "$per1000" -ge 15 ]; then echo "ВЕРДИКТ: явный ИИ-текст, переписывать";
  elif [ "$per1000" -ge 6 ];  then echo "ВЕРДИКТ: пахнет ИИ, править по списку выше";
  else echo "ВЕРДИКТ: механических маркеров нет, дальше смотреть глазами (ритм, конкретика, триады)"; fi
  return 0
}

if [ "${1:-}" = "--selftest" ]; then
  slop='В современном мире важно понимать: это не просто инструмент, а комплексное решение.
- **Скорость:** действительно быстро
Стоит отметить — мы поможем раскрыть потенциал вашего бизнеса. Надеюсь, это поможет.'
  clean='Сайт собрали за две недели. Форма отправляет заявку в Telegram, цена 45 тысяч.
Клиент проверил на телефоне, всё открывается. Правок не было.'
  s=$(scan "$slop"); c=$(scan "$clean")
  echo "$s" | grep -q "явный ИИ-текст" || { echo "FAIL: слоп не пойман"; echo "$s"; exit 1; }
  echo "$c" | grep -q "механических маркеров нет" || { echo "FAIL: чистый текст помечен"; echo "$c"; exit 1; }
  echo "OK: selftest пройден"; exit 0
fi

if [ $# -ge 1 ]; then scan "$(cat "$1")"; else scan "$(cat)"; fi
